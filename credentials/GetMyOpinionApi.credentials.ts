import {
  ME_PATH,
  PRODUCTION_ORIGIN,
  buildGmoAuthHeaders,
  resolveBaseUrl,
} from '../src/core/index.js';
import type { IAuthenticate, ICredentialDataDecryptedObject, ICredentialTestRequest, ICredentialType, IHttpRequestOptions, INodeProperties, Icon } from 'n8n-workflow';

export class GetMyOpinionApi implements ICredentialType {
  name = 'getMyOpinionApi';

  displayName = 'GetMyOpinion API';
  documentationUrl =
    'https://github.com/GetMyOpinion/n8n-nodes-getmyopinion#readme';
  icon: Icon = 'fa:key';

  properties: INodeProperties[] = [
    {
      displayName: 'Public Key',
      name: 'keyId',
      type: 'string',
      default: '',
      required: true,
      description:
        'Public key generated by the GetMyOpinion account owner. It identifies the connection and is not secret.',
    },
    {
      displayName: 'Secret',
      name: 'secret',
      type: 'string',
      typeOptions: { password: true },
      default: '',
      required: true,
      description:
        'Shown once when the key is created or rotated. Never share it.',
    },
  ];

  authenticate: IAuthenticate = async (
    credentials: ICredentialDataDecryptedObject,
    requestOptions: IHttpRequestOptions,
  ): Promise<IHttpRequestOptions> => {
    const url = new URL(requestOptions.url);

    if (url.search) {
      throw new Error(
        'Query strings are forbidden by the GetMyOpinion API contract 1.0.0. Send parameters in the request body instead.',
      );
    }

    const body =
      typeof requestOptions.body === 'string' ? requestOptions.body : '';

    const authHeaders = buildGmoAuthHeaders(
      requestOptions.method ?? 'GET',
      url.pathname,
      body,
      {
        keyId: String(credentials.keyId),
        secret: String(credentials.secret),
      },
    );

    return {
      ...requestOptions,
      headers: {
        ...requestOptions.headers,
        ...authHeaders,
        ...(requestOptions.method === 'POST'
          ? { 'Content-Type': 'application/json' }
          : {}),
      },
    };
  };

  test: ICredentialTestRequest = {
    request: {
      method: 'GET',
      url: resolveBaseUrl({ defaultOrigin: PRODUCTION_ORIGIN }) + ME_PATH,
      disableFollowRedirect: true,
      headers: {},
    },
  };
}
